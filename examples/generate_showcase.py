def _sum16(data: bytes) -> int:
    if len(data) % 2:
        data += b"\0"
    total = sum(struct.unpack(f"!{len(data)//2}H", data))
    while total >> 16:
        total = (total & 0xffff) + (total >> 16)
    return (~total) & 0xffff


def _frame(src: str, dst: str, sp: int, dp: int, seq: int, ack: int,
           flags: int, payload: bytes, ident: int) -> bytes:
    s, d = socket.inet_aton(src), socket.inet_aton(dst)
    tcp = struct.pack("!HHIIHHHH", sp, dp, seq & 0xffffffff, ack & 0xffffffff,
                      (5 << 12) | flags, 32768, 0, 0)
    pseudo = s + d + struct.pack("!BBH", 0, 6, len(tcp) + len(payload))
    tcp = tcp[:16] + struct.pack("!H", _sum16(pseudo + tcp + payload)) + tcp[18:] + payload
    ip = struct.pack("!BBHHHBBH4s4s", 0x45, 0, 20 + len(tcp), ident & 65535,
                     0x4000, 64, 6, 0, s, d)
    ip = ip[:10] + struct.pack("!H", _sum16(ip)) + ip[12:]
    return b"\x02\xaa\xbb\xcc\xdd\x01\x02\xaa\xbb\xcc\xdd\x02\x08\x00" + ip + tcp


def _messages(idx: int, scenario: tuple) -> tuple[bytes, bytes]:
    name, method, path, mode, fields, response_mode = scenario
    if mode == "json":
        body = json.dumps(fields, separators=(",", ":"), ensure_ascii=False).encode()
        body_headers = b"Content-Type: application/json\r\n"
    elif mode == "form":
        body = urlencode(fields).encode()
        body_headers = b"Content-Type: application/x-www-form-urlencoded\r\n"
    elif mode == "chunked":
        raw = json.dumps(fields, separators=(",", ":")).encode()
        first, second = raw[:len(raw)//2], raw[len(raw)//2:]
        body = (f"{len(first):X}\r\n".encode() + first + b"\r\n"
                + f"{len(second):X}\r\n".encode() + second + b"\r\n0\r\n\r\n")
        body_headers = b"Content-Type: application/json\r\nTransfer-Encoding: chunked\r\n"
    else:
        body = b""
        body_headers = b""
    framing = b"" if mode == "chunked" else f"Content-Length: {len(body)}\r\n".encode()
    secret = b"Authorization: Bearer fictional-demo-token-123\r\n" if name == "login" else b""
    request = (f"{method} {path} HTTP/1.1\r\nHost: {name}.example.test\r\n".encode()
               + body_headers + secret + framing + b"Connection: close\r\n\r\n" + body)

    response_fields = ({"result": "accepted", "scenario": name,
                        "email": "response@example.test"} if idx in (0, 3, 11)
                       else {"result": "accepted", "scenario": name})
    response_plain = json.dumps(response_fields, separators=(",", ":")).encode()
    extra = b""
    if response_mode == "gzip":
        response_body = gzip.compress(response_plain, mtime=0)
        extra = b"Content-Encoding: gzip\r\n"
    elif response_mode == "chunked":
        response_body = f"{len(response_plain):X}\r\n".encode() + response_plain + b"\r\n0\r\n\r\n"
    else:
        response_body = response_plain
    response_headers = (b"Transfer-Encoding: chunked\r\n" if response_mode == "chunked"
                        else f"Content-Length: {len(response_body)}\r\n".encode())
    response = (b"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n"
                + extra + response_headers + b"Connection: close\r\n\r\n" + response_body)
    return request, response


def packets() -> list[tuple[float, bytes]]:
    result = []
    ident = 0
    for i, scenario in enumerate(SCENARIOS):
        request, response = _messages(i, scenario)
        src, dst = CLIENT + str(10 + i), SERVER + str(20 + i % 3)
        sport, dport = 42000 + i, 80
        cseq, sseq = 10000 + i * 4000, 20000 + i * 5000
        t = BASE_TIME + i * 0.25
        def emit(a, b, ap, bp, seq, ack, flags, payload=b""):
            nonlocal ident
            result.append((t + len(result) * 0.000001,
                           _frame(a, b, ap, bp, seq, ack, flags, payload, ident)))
            ident += 1
        emit(src, dst, sport, dport, cseq, 0, 0x02)
        emit(dst, src, dport, sport, sseq, cseq+1, 0x12)
        emit(src, dst, sport, dport, cseq+1, sseq+1, 0x10)
        # Segment large messages; the TCP reassembler must combine segments.
        part = max(32, len(request)//3)
        chunks = [(j, request[j:j+part]) for j in range(0, len(request), part)]
        if i % 3 == 0 and len(chunks) > 1:
            chunks[0], chunks[1] = chunks[1], chunks[0]  # captured out of order
        for j, chunk in chunks:
            emit(src, dst, sport, dport, cseq+1+j, sseq+1, 0x18, chunk)
        if i % 4 == 0:
            j, chunk = chunks[-1]
            emit(src, dst, sport, dport, cseq+1+j, sseq+1, 0x18, chunk)  # retransmission
        emit(dst, src, dport, sport, sseq+1, cseq+1+len(request), 0x18, response)
    return result


def write_pcap(path: Path) -> None:
    """Write the complete synthetic file. Never uses real captures or live sockets."""
    with open(path, "xb") as out:
        out.write(struct.pack("<IHHIIII", 0xa1b2c3d4, 2, 4, 0, 0, 65535, 1))
        for timestamp, frame in packets():
            seconds = int(timestamp)
            micros = int(round((timestamp - seconds) * 1_000_000))
            out.write(struct.pack("<IIII", seconds, micros, len(frame), len(frame)))
            out.write(frame)


